export type GlyphClass = "solid" | "soft" | "dim" | "faint" | "space";

const classOf = (ch: string): GlyphClass =>
  ch === "#"
    ? "solid"
    : ch === "*"
      ? "soft"
      : ch === ":"
        ? "dim"
        : ch === "."
          ? "faint"
          : "space";

export type Run = { text: string; glyph: GlyphClass };

export const RUNS: Run[][] = BUTTERFLY.map((line) => {
  const runs: Run[] = [];
  for (const ch of line) {
    const glyph = classOf(ch);
    const last = runs[runs.length - 1];
    if (last && last.glyph === glyph) last.text += ch;
    else runs.push({ text: ch, glyph });
  }
  return runs;
});

/* Widest line, in characters. The panel sizes the type from this so the
 * whole butterfly always fits its container at any width. */
export const COLUMNS = Math.max(...BUTTERFLY.map((l) => l.length));
